#!/usr/bin/env bash
# Generates WebP variants (640px and up to 1280px wide) for every .jpg referenced in
# src/config.ts and writes src/lib/responsiveImages.ts (used for srcSet in <img>).
# Re-run after adding or replacing a photo:  bash scripts/build-responsive-images.sh
# Requires ffmpeg + ffprobe.
set -euo pipefail
cd "$(dirname "$0")/.."
out=src/lib/responsiveImages.ts
{
  echo "// GENERATED by scripts/build-responsive-images.sh — do not edit by hand."
  echo "// Maps an original /public JPG path to its WebP variants for srcSet."
  echo "export const responsiveImages: Record<string, { small: string; large: string; largeWidth: number }> = {"
} > "$out"
for src in $(grep -o 'assetPath("/[^"]*\.jpg")' src/config.ts | grep -o '/[^"]*\.jpg' | sort -u); do
  f="public$src"; base="${src%.jpg}"
  w=$(ffprobe -v error -select_streams v:0 -show_entries stream=width -of csv=p=0 "$f")
  lw=$(( w < 1280 ? w : 1280 ))
  ffmpeg -y -loglevel error -i "$f" -vf "scale=640:-2" -c:v libwebp -quality 78 -map_metadata -1 "public${base}-640.webp"
  ffmpeg -y -loglevel error -i "$f" -vf "scale=${lw}:-2" -c:v libwebp -quality 78 -map_metadata -1 "public${base}-${lw}.webp"
  echo "  '${src}': { small: '${base}-640.webp', large: '${base}-${lw}.webp', largeWidth: ${lw} }," >> "$out"
done
echo "};" >> "$out"
echo "Wrote $out"
